import { createVinylSuite, vinylTestAssets } from '@amazon/vinyl/vinylTestUtil'
import {
    type AdBreakCompleteEvent,
    type AdCompleteEvent,
    type AdEvent,
    supportsMse,
    type VinylPlayer,
    type VinylTrackLoadOptions,
} from '@amazon/vinyl'
import { poll } from '@amazon/vinyl-util'

/**
 * Integration tests for stitched (SSAI) ad breaks signalled with SCTE-35 in
 * DASH MPD events and HLS EXT-X-DATERANGE tags, and for DASH alternative MPD
 * (SGAI) events. Assets are generated by DMTestAssetBuilder; see its
 * docs/AD_BREAK_ASSETS.md for each scenario's timeline.
 */
describe('ad insertion integ', () => {
    const suite = createVinylSuite({}, { timeout: 180, failOnError: false })

    beforeEach(() => {
        if (!supportsMse()) pending('MSE not supported')
    })

    interface Recorded {
        readonly breaksEntered: string[]
        readonly breaksCompleted: AdBreakCompleteEvent[]
        readonly adsEntered: AdEvent[]
        readonly adsCompleted: AdCompleteEvent[]
        dispose(): void
    }

    function record(player: VinylPlayer): Recorded {
        const recorded = {
            breaksEntered: [] as string[],
            breaksCompleted: [] as AdBreakCompleteEvent[],
            adsEntered: [] as AdEvent[],
            adsCompleted: [] as AdCompleteEvent[],
        }
        const subs = [
            player.on('adBreakEntered', (e) =>
                recorded.breaksEntered.push(e.adBreak.id)
            ),
            player.on('adBreakCompleted', (e) =>
                recorded.breaksCompleted.push(e)
            ),
            player.on('adEntered', (e) => recorded.adsEntered.push(e)),
            player.on('adCompleted', (e) => recorded.adsCompleted.push(e)),
        ]
        return {
            ...recorded,
            dispose: () => subs.forEach((unsub) => unsub()),
        }
    }

    async function loadAndAwaitAdBreaks(
        options: VinylTrackLoadOptions
    ): Promise<void> {
        suite.player.load(options)
        expect(
            await poll(
                () => (suite.player.currentTrackAds?.adBreaks.length ?? 0) > 0,
                { timeout: 20 }
            )
        )
            .withContext('ad breaks discovered')
            .toBeTrue()
    }

    /**
     * Plays then seeks; seeking a never-played MSE element hangs on iOS
     * Safari.
     */
    async function playThenSeek(time: number): Promise<void> {
        await suite.player.play().catch(() => undefined)
        await suite.player.seekTo(time, 0.5).catch(() => undefined)
    }

    async function expectPlaysTo(time: number, timeout = 30): Promise<void> {
        expect(await poll(() => suite.player.currentTime >= time, { timeout }))
            .withContext(`plays to ${time}`)
            .toBeTrue()
    }

    describe('dash stitched SCTE-35', () => {
        const XML_BIN: VinylTrackLoadOptions = {
            type: 'dash',
            uri: vinylTestAssets.dash.vinyl_ad_breaks_av__ssai_scte35_xmlbin,
        }

        it('discovers an xml+bin avail as a stitched break of its ad Periods', async () => {
            await loadAndAwaitAdBreaks(XML_BIN)
            const [adBreak, ...rest] = suite.player.currentTrackAds!.adBreaks
            expect(rest).toEqual([])
            expect(adBreak).toEqual(
                jasmine.objectContaining({
                    startTime: 60,
                    duration: 15,
                    placement: 'midroll',
                    insertion: 'stitched',
                })
            )
            expect(adBreak.signal?.scte35[0].command.type).toBe('spliceInsert')
            expect(adBreak.ads).toEqual([
                jasmine.objectContaining({
                    startTime: 60,
                    duration: 15,
                    uri: null,
                }),
            ])
        })

        it('discovers an xml avail', async () => {
            await loadAndAwaitAdBreaks({
                type: 'dash',
                uri: vinylTestAssets.dash.vinyl_ad_breaks_av__ssai_scte35_xml,
            })
            expect(suite.player.currentTrackAds!.adBreaks).toEqual([
                jasmine.objectContaining({
                    startTime: 60,
                    duration: 15,
                    insertion: 'stitched',
                }),
            ])
        })

        it('plays through a stitched break on the content track', async () => {
            await loadAndAwaitAdBreaks(XML_BIN)
            const player = suite.player
            const contentTrack = player.activeTrack
            const recorded = record(player)
            try {
                await playThenSeek(58)
                await expectPlaysTo(61)
                expect(recorded.breaksEntered.length).toBe(1)
                expect(player.currentAdBreak?.insertion).toBe('stitched')
                expect(player.currentAd).not.toBeNull()
                expect(player.activeTrack).toBe(contentTrack)
                // Playback crosses the ad Period back into content.
                await playThenSeek(73)
                await expectPlaysTo(76)
                expect(recorded.breaksCompleted.at(-1)?.reason).toBe('ended')
                expect(player.currentAdBreak).toBeNull()
                expect(player.activeTrack).toBe(contentTrack)
            } finally {
                recorded.dispose()
            }
        })

        it('skips a stitched break by seeking past it', async () => {
            await loadAndAwaitAdBreaks(XML_BIN)
            const player = suite.player
            const recorded = record(player)
            try {
                await playThenSeek(61)
                expect(
                    await poll(() => player.currentAdBreak != null, {
                        timeout: 30,
                    })
                )
                    .withContext('in break')
                    .toBeTrue()
                player.skipAdBreak()
                expect(player.currentAdBreak).toBeNull()
                expect(recorded.breaksCompleted.at(-1)?.reason).toBe('skipped')
                await expectPlaysTo(76)
            } finally {
                recorded.dispose()
            }
        })

        it('plays each ad of a time_signal pod', async () => {
            await loadAndAwaitAdBreaks({
                type: 'dash',
                uri: vinylTestAssets.dash
                    .vinyl_ad_breaks_av__ssai_pod_time_signal,
            })
            const player = suite.player
            const [adBreak] = player.currentTrackAds!.adBreaks
            expect(adBreak.duration).toBe(25)
            expect(adBreak.ads).toEqual([
                jasmine.objectContaining({ startTime: 60, duration: 20 }),
                jasmine.objectContaining({ startTime: 80, duration: 5 }),
            ])
            const recorded = record(player)
            try {
                await playThenSeek(78.5)
                await expectPlaysTo(81)
                expect(recorded.adsCompleted.map((e) => e.reason)).toEqual([
                    'ended',
                ])
                expect(player.currentAd?.startTime).toBe(80)
            } finally {
                recorded.dispose()
            }
        })

        it('enters a stitched preroll from the start', async () => {
            await loadAndAwaitAdBreaks({
                type: 'dash',
                uri: vinylTestAssets.dash.vinyl_ad_breaks_av__ssai_pre_mid_post,
            })
            const player = suite.player
            expect(
                player.currentTrackAds!.adBreaks.map((b) => [
                    b.startTime,
                    b.placement,
                ])
            ).toEqual([
                [0, 'preroll'],
                [90, 'midroll'],
                [200, 'postroll'],
            ])
            await player.play()
            expect(
                await poll(
                    () => player.currentAdBreak?.placement === 'preroll',
                    {
                        timeout: 30,
                    }
                )
            )
                .withContext('preroll entered')
                .toBeTrue()
            await expectPlaysTo(1)
        })
    })

    describe('dash alternative MPD', () => {
        it('plays an inserted preroll as an interstitial, then content', async () => {
            await loadAndAwaitAdBreaks({
                type: 'dash',
                uri: vinylTestAssets.dash.vinyl_ad_breaks_av__altmpd_insert,
            })
            const player = suite.player
            const breaks = player.currentTrackAds!.adBreaks
            expect(
                breaks.map((b) => [b.startTime, b.placement, b.insertion])
            ).toEqual([
                [0, 'preroll', 'interstitial'],
                [60, 'midroll', 'interstitial'],
            ])
            expect(breaks[1]).toEqual(
                jasmine.objectContaining({
                    resumeOffset: 0,
                    playoutLimit: 15,
                    resolutionTimeOffset: 10,
                })
            )
            const recorded = record(player)
            try {
                await player.play().catch(() => undefined)
                expect(
                    await poll(() => player.currentAd?.uri != null, {
                        timeout: 30,
                    })
                )
                    .withContext('preroll ad active')
                    .toBeTrue()
                expect(player.activeTrack?.uri).toBe(player.currentAd!.uri!)
                player.skipAdBreak()
                expect(
                    await poll(
                        () =>
                            player.activeTrack?.uri ===
                            vinylTestAssets.dash
                                .vinyl_ad_breaks_av__altmpd_insert,
                        { timeout: 30 }
                    )
                )
                    .withContext('content resumed')
                    .toBeTrue()
            } finally {
                recorded.dispose()
            }
        })

        it('resumes a replaced span at its return offset', async () => {
            await loadAndAwaitAdBreaks({
                type: 'dash',
                uri: vinylTestAssets.dash.vinyl_ad_breaks_av__altmpd_replace,
            })
            const player = suite.player
            const [adBreak] = player.currentTrackAds!.adBreaks
            expect(adBreak).toEqual(
                jasmine.objectContaining({
                    startTime: 60,
                    duration: 15,
                    resumeOffset: 15,
                    insertion: 'interstitial',
                })
            )
            const recorded = record(player)
            try {
                await playThenSeek(59)
                expect(
                    await poll(() => player.currentAd?.uri != null, {
                        timeout: 30,
                    })
                )
                    .withContext('replacement ad active')
                    .toBeTrue()
                player.skipAdBreak()
                expect(recorded.breaksCompleted.at(-1)?.resumePosition).toBe(75)
                await expectPlaysTo(75.5)
            } finally {
                recorded.dispose()
            }
        })
    })

    describe('dash list MPDs and remote elements', () => {
        it('plays a list MPD, reporting its signalled ad Periods as stitched breaks', async () => {
            await loadAndAwaitAdBreaks({
                type: 'dash',
                uri: vinylTestAssets.dash.vinyl_ad_breaks_av__list_mpd,
            })
            const player = suite.player
            expect(
                player.currentTrackAds!.adBreaks.map((b) => [
                    b.startTime,
                    b.duration,
                    b.placement,
                    b.insertion,
                ])
            ).toEqual([
                [0, 30, 'preroll', 'stitched'],
                [185, 10, 'postroll', 'stitched'],
            ])
            expect(player.seekRange?.end).toBeCloseTo(195, 0)
            const recorded = record(player)
            try {
                // Crosses from the imported preroll into the imported content.
                await playThenSeek(28.5)
                expect(
                    await poll(
                        () => player.currentAdBreak?.placement === 'preroll',
                        { timeout: 30 }
                    )
                )
                    .withContext('in the stitched preroll')
                    .toBeTrue()
                await expectPlaysTo(31)
                expect(recorded.breaksCompleted.at(-1)?.reason).toBe('ended')
                expect(player.currentAdBreak).toBeNull()
            } finally {
                recorded.dispose()
            }
        })

        it('plays each ad of an alternative MPD list pod', async () => {
            await loadAndAwaitAdBreaks({
                type: 'dash',
                uri: vinylTestAssets.dash.vinyl_ad_breaks_av__altmpd_list,
            })
            const player = suite.player
            const [adBreak] = player.currentTrackAds!.adBreaks
            expect(adBreak).toEqual(
                jasmine.objectContaining({
                    startTime: 60,
                    insertion: 'interstitial',
                    playoutLimit: 25,
                })
            )
            const recorded = record(player)
            try {
                await playThenSeek(59)
                expect(
                    await poll(() => recorded.adsEntered.length > 0, {
                        timeout: 30,
                    })
                )
                    .withContext('first ad entered')
                    .toBeTrue()
                const [first] = recorded.adsEntered
                expect(first.totalAds).toBe(2)
                expect(first.ad.uri).toMatch(/ad_spot-a\/manifest\.mpd$/)
                expect(
                    await poll(() => player.activeTrack?.uri === first.ad.uri, {
                        timeout: 30,
                    })
                )
                    .withContext('first ad track active')
                    .toBeTrue()
                // Skipping the first ad advances to the second, which plays to
                // its end, completing the break.
                player.skipAd()
                expect(
                    await poll(() => recorded.adsEntered.length > 1, {
                        timeout: 30,
                    })
                )
                    .withContext('second ad entered')
                    .toBeTrue()
                const second = recorded.adsEntered[1]
                expect(second.index).toBe(1)
                expect(second.ad.uri).toMatch(/ad_spot-b\/manifest\.mpd$/)
                expect(
                    await poll(() => recorded.breaksCompleted.length > 0, {
                        timeout: 30,
                    })
                )
                    .withContext('break completed')
                    .toBeTrue()
                expect(recorded.adsCompleted.map((e) => e.reason)).toEqual([
                    'skipped',
                    'ended',
                ])
                // An insert resumes where content paused.
                expect(recorded.breaksCompleted[0].resumePosition).toBeCloseTo(
                    60,
                    0
                )
            } finally {
                recorded.dispose()
            }
        })

        it('resolves a remote Period into a stitched pod', async () => {
            await loadAndAwaitAdBreaks({
                type: 'dash',
                uri: vinylTestAssets.dash
                    .vinyl_ad_breaks_av__xlink_remote_period,
            })
            const player = suite.player
            const [adBreak, ...rest] = player.currentTrackAds!.adBreaks
            expect(rest).toEqual([])
            expect(adBreak).toEqual(
                jasmine.objectContaining({
                    startTime: 60,
                    duration: 25,
                    insertion: 'stitched',
                })
            )
            expect(adBreak.ads).toEqual([
                jasmine.objectContaining({ startTime: 60, duration: 20 }),
                jasmine.objectContaining({ startTime: 80, duration: 5 }),
            ])
            const recorded = record(player)
            try {
                await playThenSeek(78.5)
                await expectPlaysTo(81)
                expect(recorded.adsCompleted.map((e) => e.reason)).toEqual([
                    'ended',
                ])
            } finally {
                recorded.dispose()
            }
        })
    })

    describe('hls stitched SCTE-35', () => {
        it('merges SCTE35-OUT and SCTE35-IN into a stitched break', async () => {
            await loadAndAwaitAdBreaks({
                type: 'hls',
                uri: vinylTestAssets.hls.vinyl_ad_breaks_av__ssai_scte35,
            })
            const [adBreak, ...rest] = suite.player.currentTrackAds!.adBreaks
            expect(rest).toEqual([])
            expect(adBreak).toEqual(
                jasmine.objectContaining({
                    id: 'splice-1',
                    duration: 15,
                    insertion: 'stitched',
                })
            )
            expect(adBreak.startTime).toBeCloseTo(60, 1)
            expect(adBreak.signal?.scte35.length).toBe(2)
        })

        it('plays across the ad discontinuities of a SCTE35-CMD pod', async () => {
            await loadAndAwaitAdBreaks({
                type: 'hls',
                uri: vinylTestAssets.hls.vinyl_ad_breaks_av__ssai_scte35_cmd,
            })
            const player = suite.player
            const [adBreak] = player.currentTrackAds!.adBreaks
            expect(adBreak.duration).toBe(25)
            expect((adBreak.ads as readonly unknown[]).length).toBe(2)
            const recorded = record(player)
            try {
                await playThenSeek(78.5)
                await expectPlaysTo(81)
                expect(recorded.adsCompleted.map((e) => e.reason)).toEqual([
                    'ended',
                ])
                await playThenSeek(84)
                await expectPlaysTo(86)
                expect(recorded.breaksCompleted.at(-1)?.reason).toBe('ended')
            } finally {
                recorded.dispose()
            }
        })
    })
})
